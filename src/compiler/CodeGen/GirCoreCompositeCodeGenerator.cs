using BluePrint.Compiler.Syntax;

namespace BluePrint.Compiler.CodeGen;

public sealed class GirCoreCompositeCodeGenerator(TextWriter writer) : IDisposable
{
    private readonly TextWriter _writer = writer;

    public void Visit(Document document, string resourceName)
    {
        _writer.WriteLine("/// <auto-generated />");

        TemplateVisitor.Visit(document, template =>
        {
            NameSpace(template.TypeName, () =>
            {
                if (template.BaseName is { } baseName)
                    _writer.WriteLine($"[global::GObject.Subclass<global::{TypeName(baseName)}>]");

                _writer.WriteLine($$"""
                [global::Gtk.Template<global::Gtk.AssemblyResource>("{{resourceName}}")]
                partial class {{ClassName(template.TypeName)}}
                """);

                Block(() => ObjectLiteralVisitor.Visit(template, obj =>
                {
                    if (obj.Id is not { } id)
                        return;

                    _writer.WriteLine($"""
                    [global::Gtk.Connect("{id}")]
                    private {TypeName(obj.TypeName)} {Identifier(id)};
                    """);
                }));
            });
        });
    }

    private void NameSpace(TypeName typeName, Action action)
    {
        var @namespace = typeName.Parts.ToArray() switch
        {
            [] or [_] => null,
            [.. var @namespaceParts, _] => string.Join('.', @namespaceParts),
        };

        if (@namespace is null)
        {
            action();
            return;
        }

        _writer.WriteLine($"namespace {@namespace}");
        Block(action);
    }

    private void Block(Action action)
    {
        _writer.WriteLine("{");
        action();
        _writer.WriteLine("}");
    }

    private static string ClassName(TypeName typeName)
        => typeName.Parts[typeName.Parts.Count - 1];

    private static string TypeName(TypeName typeName)
        => string.Join('.', typeName.Parts);

    private static string Identifier(string value)
        => string.Create(value.Length, value, (target, source) =>
        {
            for (int i = 0; i < source.Length; i++)
            {
                target[i] = source[i] switch
                {
                    '-' => '_',
                    var c => c,
                };
            }
        });

    public void Dispose()
        => _writer.Dispose();
}

file sealed class TemplateVisitor(Action<Template> action) : ISyntaxVisitor
{
    void ISyntaxVisitor.VisitDefault<T>(T element)
        => element.VisitChildren(this);

    void ISyntaxVisitor.VisitTemplate(Template template) => action(template);

    public static void Visit(Document document, Action<Template> action)
    {
        TemplateVisitor visitor = new(action);
        document.Visit(visitor);
    }
}

file sealed class ObjectLiteralVisitor(Action<ObjectLiteral> action) : ISyntaxVisitor
{
    void ISyntaxVisitor.VisitDefault<T>(T element)
        => element.VisitChildren(this);

    void ISyntaxVisitor.VisitObject(ObjectLiteral @object) => action(@object);

    public static void Visit(Template template, Action<ObjectLiteral> action)
    {
        ObjectLiteralVisitor visitor = new(action);
        template.Visit(visitor);
    }
}
