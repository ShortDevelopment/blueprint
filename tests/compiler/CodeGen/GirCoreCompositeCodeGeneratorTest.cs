namespace BluePrint.Compiler.CodeGen;

public class GirCoreCompositeCodeGeneratorTest
{
    [Test]
    public async Task NestedObjects()
    {
        await AssertGenerator(
            resourceName: "MyClass.ui",
            source: """
            using Gtk 4.0;
            using Adw 1;

            template $MyApp.Controls.MyControl : Adw.Window {
              content: Adw.ToolbarView {
                [top]
                Adw.HeaderBar {
                  title-widget: Adw.ViewSwitcher { };

                  [end]
                  Gtk.MenuButton MenuButton { }
                }

                content: Gtk.Box {
                  Adw.Banner { }

                  Adw.ViewStack Stack {
                    Adw.ViewStackPage {
                      child: Adw.Clamp SendPage {
                        Adw.PreferencesPage {
                          Adw.PreferencesGroup {
                            Adw.ActionRow ShareFileAction { }
                            Adw.ActionRow ShareClipboardAction { }
                          }
                        }
                      };
                    }
                  }
                };

                [bottom]
                Adw.ViewSwitcherBar SwitchBar {
                  stack: Stack;
                }
              };
            }
            
            """,
            """
            /// <auto-generated />
            namespace MyApp.Controls
            {
            [global::GObject.Subclass<global::Adw.Window>]
            [global::Gtk.Template<global::Gtk.AssemblyResource>("MyClass.ui")]
            partial class MyControl
            {
            [global::Gtk.Connect("MenuButton")]
            private Gtk.MenuButton MenuButton;
            [global::Gtk.Connect("Stack")]
            private Adw.ViewStack Stack;
            [global::Gtk.Connect("SendPage")]
            private Adw.Clamp SendPage;
            [global::Gtk.Connect("ShareFileAction")]
            private Adw.ActionRow ShareFileAction;
            [global::Gtk.Connect("ShareClipboardAction")]
            private Adw.ActionRow ShareClipboardAction;
            [global::Gtk.Connect("SwitchBar")]
            private Adw.ViewSwitcherBar SwitchBar;
            }
            }

            """
        );
    }

    private static async Task AssertGenerator(string resourceName, string source, string expected)
    {
        using StringWriter writer = new();
        using GirCoreCompositeCodeGenerator generator = new(writer);
        generator.Visit(Parser.Parser.Parse(source), resourceName);
        var actual = writer.ToString();

        await Assert.That(actual.ReplaceLineEndings())
            .IsEqualTo(expected.ReplaceLineEndings());
    }
}
